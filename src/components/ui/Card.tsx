import React from 'react';
import { cn } from '../../lib/utils';

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  variant?: 'default' | 'subtle' | 'interactive';
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, variant = 'default', children, ...props }, ref) => {
    const variants = {
      default: 'bg-white border border-zinc-200 shadow-xs',
      subtle: 'bg-zinc-50/70 border border-zinc-200/80',
      interactive:
        'bg-white border border-zinc-200 shadow-xs hover:border-zinc-300 hover:shadow-sm cursor-pointer transition-all duration-150',
    };

    return (
      <div
        ref={ref}
        className={cn('rounded-lg p-5 sm:p-6', variants[variant], className)}
        {...props}
      >
        {children}
      </div>
    );
  }
);
Card.displayName = 'Card';

